const cellKey = (cx: number, cz: number): number => (cx & 0xffff) * 65536 + (cz & 0xffff);
const bucketKey = (x: number, z: number): number =>
  cellKey(Math.floor(x / BUCKET), Math.floor(z / BUCKET));

// --------------------------------------------------------- presentation

/**
 * The palette the whole visual language of the air is built from. Linear RGB,
 * because everything downstream tonemaps. These are not arbitrary: warm for
 * air that is doing you a favour, cold for air that is taking from you, and
 * one genuinely otherworldly cyan for the wave, which should not look like
 * anything else in the game.
 */
const KIND_COLORS: Record<AirKind, { r: number; g: number; b: number }> = {
  [AirKind.Still]: { r: 0.3, g: 0.33, b: 0.38 },
  [AirKind.Thermal]: { r: 1.0, g: 0.72, b: 0.32 },
  [AirKind.Ridge]: { r: 0.72, g: 0.92, b: 0.66 },
  [AirKind.Wave]: { r: 0.56, g: 0.92, b: 1.0 },
  [AirKind.Rotor]: { r: 0.66, g: 0.52, b: 0.78 },
  [AirKind.Convergence]: { r: 1.0, g: 0.68, b: 0.76 },
  [AirKind.Sink]: { r: 0.34, g: 0.5, b: 0.72 },
};

export function airKindColor(kind: AirKind): { r: number; g: number; b: number } {
  return KIND_COLORS[kind] ?? KIND_COLORS[AirKind.Still];
}

const KIND_LABELS: Record<AirKind, string> = {
  [AirKind.Still]: '—',
  [AirKind.Thermal]: 'thermal',
  [AirKind.Ridge]: 'ridge lift',
  [AirKind.Wave]: 'wave',
  [AirKind.Rotor]: 'rotor',
  [AirKind.Convergence]: 'convergence',
  [AirKind.Sink]: 'sink',
};

export function airKindLabel(kind: AirKind): string {
  return KIND_LABELS[kind] ?? '—';
}
